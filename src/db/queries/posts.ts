import type { Post } from "@prisma/client";
import { db } from "@/db";

export type PostWithData = Post & {
  topic: { slug: string };
  user: { name: string | null };
  _count: { comments: number };
};

// export type PostWithData = Awaited<ReturnType<typeof fetchPostsByTopicSlug>>[number] 
